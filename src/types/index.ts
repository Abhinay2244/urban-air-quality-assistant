/**
 * Household composition types used to tailor air quality recommendations.
 */
export enum FamilyType {
  SINGLE = 'SINGLE',
  COUPLE = 'COUPLE',
  NUCLEAR = 'NUCLEAR',
  MULTI_GENERATIONAL = 'MULTI_GENERATIONAL',
}

/**
 * Primary daily commute modes affecting personal pollution exposure and emissions.
 */
export enum CommuteMode {
  CAR = 'CAR',
  PUBLIC_TRANSIT = 'PUBLIC_TRANSIT',
  WALK_OR_BIKE = 'WALK_OR_BIKE',
  MIXED = 'MIXED',
  REMOTE = 'REMOTE',
}

/**
 * Dwelling types affecting indoor ventilation and filtration strategies.
 */
export enum HomeType {
  APARTMENT = 'APARTMENT',
  DETACHED_HOUSE = 'DETACHED_HOUSE',
  TOWNHOUSE = 'TOWNHOUSE',
  SHARED_HOUSING = 'SHARED_HOUSING',
}

/**
 * Actionable recommendation categories generated by the assistant.
 */
export enum RecommendationCategory {
  DAILY_ROUTINE = 'DAILY_ROUTINE',
  INDOOR_AIR = 'INDOOR_AIR',
  SUSTAINABLE_ALTERNATIVE = 'SUSTAINABLE_ALTERNATIVE',
  HEALTH_ALERT = 'HEALTH_ALERT',
}

/**
 * Urgency tier assigned dynamically by the rule engine.
 */
export enum UrgencyLevel {
  CRITICAL = 'CRITICAL',
  HIGH = 'HIGH',
  STANDARD = 'STANDARD',
}

/**
 * Standard US EPA AQI category identifiers.
 */
export enum AQICategoryId {
  GOOD = 'GOOD',
  MODERATE = 'MODERATE',
  UNHEALTHY_SENSITIVE = 'UNHEALTHY_SENSITIVE',
  UNHEALTHY = 'UNHEALTHY',
  VERY_UNHEALTHY = 'VERY_UNHEALTHY',
  HAZARDOUS = 'HAZARDOUS',
}

/**
 * Application-wide typed error codes.
 */
export enum ErrorCode {
  VALIDATION_ERROR = 'VALIDATION_ERROR',
  CITY_NOT_FOUND = 'CITY_NOT_FOUND',
  AQI_FETCH_ERROR = 'AQI_FETCH_ERROR',
  AI_SERVICE_ERROR = 'AI_SERVICE_ERROR',
  PARSE_ERROR = 'PARSE_ERROR',
  NETWORK_ERROR = 'NETWORK_ERROR',
  UNKNOWN_ERROR = 'UNKNOWN_ERROR',
}

/**
 * Household and lifestyle profile supplied by the user.
 */
export interface UserProfile {
  city: string;
  familyType: FamilyType;
  hasChildren: boolean;
  hasElderly: boolean;
  hasRespiratoryCondition: boolean;
  commuteMode: CommuteMode;
  homeType: HomeType;
}

/**
 * Current air quality measurements and derived classification for a city.
 */
export interface AQIData {
  city: string;
  country: string;
  aqi: number;
  pm25: number;
  pm10: number;
  no2: number;
  o3: number;
  category: AQICategoryId;
  updatedAt: string;
  source?: 'live' | 'manual';
}

/**
 * Metadata and health guidance for a single AQI tier.
 */
export interface AQICategoryInfo {
  id: AQICategoryId;
  label: string;
  minAqi: number;
  maxAqi: number;
  colorHex: string;
  badgeClass: string;
  healthGuidance: string;
}

/**
 * Individual tailored action and its explained exposure/emission impact.
 */
export interface Recommendation {
  title: string;
  category: RecommendationCategory;
  action: string;
  impactExplanation: string;
  estimatedPM25Reduction: number;
  urgency?: UrgencyLevel;
}

/**
 * Structured output returned by the GenAI air quality assistant.
 */
export interface AssistantResponse {
  summary: string;
  priorityGuidance: string;
  recommendations: Recommendation[];
  isFallback: boolean;
}

/**
 * Typed, user-friendly error structure used across services and hooks.
 */
export interface AppError {
  code: ErrorCode;
  message: string;
  details?: string;
}
