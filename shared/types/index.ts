export type HomeType = (typeof HomeType)[keyof typeof HomeType];

/** Actionable recommendation categories generated by the assistant. */
export const RecommendationCategory = {
  DAILY_ROUTINE: 'DAILY_ROUTINE',
  INDOOR_AIR: 'INDOOR_AIR',
  SUSTAINABLE_ALTERNATIVE: 'SUSTAINABLE_ALTERNATIVE',
  HEALTH_ALERT: 'HEALTH_ALERT',
} as const;
export type RecommendationCategory =
  (typeof RecommendationCategory)[keyof typeof RecommendationCategory];

/** Urgency tier assigned dynamically by the rule engine. */
export const UrgencyLevel = {
  CRITICAL: 'CRITICAL',
  HIGH: 'HIGH',
  STANDARD: 'STANDARD',
} as const;
export type UrgencyLevel = (typeof UrgencyLevel)[keyof typeof UrgencyLevel];

/** US EPA AQI category identifiers used by WAQI and Open-Meteo (US scale). */
export const AqiCategoryId = {
  GOOD: 'GOOD',
  MODERATE: 'MODERATE',
  UNHEALTHY_SENSITIVE: 'UNHEALTHY_SENSITIVE',
  UNHEALTHY: 'UNHEALTHY',
  VERY_UNHEALTHY: 'VERY_UNHEALTHY',
  HAZARDOUS: 'HAZARDOUS',
} as const;
export type AqiCategoryId = (typeof AqiCategoryId)[keyof typeof AqiCategoryId];

/** Application-wide typed error codes. */
export const ErrorCode = ERROR_CODES;
export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];

/** Household and lifestyle profile supplied by the user. */
export interface UserProfile {
  city: string;
  familyType: FamilyType;
  hasChildren: boolean;
  hasElderly: boolean;
  hasRespiratoryCondition: boolean;
  commuteMode: CommuteMode;
  homeType: HomeType;
}

/** Single hourly PM2.5 forecast reading for outdoor activity timing. */
export interface HourlyPm25Point {
  time: string;
  pm25: number;
}

/** Upstream live AQI provider identifier. */
export type AqiProvider = 'waqi' | 'open-meteo';

/** Current air quality measurements and derived US-scale classification. */
export interface AqiData {
  city: string;
  country: string;
  stationName?: string;
  provider?: AqiProvider;
  locationWarning?: string;
  aqi: number;
  pm25: number;
  pm10?: number;
  no2?: number;
  o3?: number;
  category: AqiCategoryId;
  updatedAt?: string;
  hourlyPm25?: HourlyPm25Point[];
  source?: 'live' | 'manual';
}

/** Metadata and health guidance for a single AQI tier. */
export interface AqiCategoryInfo {
  id: AqiCategoryId;
  label: string;
  minAqi: number;
  maxAqi: number;
  healthGuidance: string;
}

/** Individual tailored action and its explained exposure/emission impact. */
export interface Recommendation {
  title: string;
  category: RecommendationCategory;
  action: string;
  impactExplanation: string;
  estimatedPM25Reduction: number;
  urgency?: UrgencyLevel;
}

/** Structured output returned by the GenAI air quality assistant. */
export interface AssistantResponse {
  summary: string;
  priorityGuidance: string;
  recommendations: Recommendation[];
  isFallback: boolean;
}

/** Typed, user-friendly error structure used across services and hooks. */
export interface AppError {
  code: ErrorCode;
  message: string;
  details?: string;
}
